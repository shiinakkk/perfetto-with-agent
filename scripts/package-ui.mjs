import {createHash} from 'node:crypto';
import {cpSync, copyFileSync, existsSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {build} from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const release = 'v59.1';
const archive = path.join(root, 'upstream', `perfetto-ui-${release}.zip`);
const output = path.join(root, 'ui-dist');
const revision = JSON.parse(readFileSync(path.join(root, 'upstream-revision.json'), 'utf8'));
const expectedHash = revision.release_ui_sha256;

if (!existsSync(archive)) {
  mkdirSync(path.dirname(archive), {recursive: true});
  console.log(`Downloading the official Perfetto ${release} UI...`);
  const response = await fetch(`https://github.com/google/perfetto/releases/download/${release}/perfetto-ui.zip`);
  if (!response.ok) throw new Error(`Official UI download failed: HTTP ${response.status}`);
  writeFileSync(archive, Buffer.from(await response.arrayBuffer()));
}
const archiveHash = createHash('sha256').update(readFileSync(archive)).digest('hex');
if (expectedHash && archiveHash !== expectedHash) {
  throw new Error(`Official UI archive hash mismatch. Expected ${expectedHash}, got ${archiveHash}`);
}
if (existsSync(output) && !existsSync(path.join(output, 'collab-manifest.json'))) {
  throw new Error(`${output} exists but was not generated by this script. Move it aside before packaging.`);
}

mkdirSync(path.join(root, 'state'), {recursive: true});
const stagingRoot = mkdtempSync(path.join(root, 'state', 'package-ui-'));
const unpacked = path.join(stagingRoot, 'unpacked');
mkdirSync(unpacked, {recursive: true});
const unzip = spawnSync('python', ['-m', 'zipfile', '-e', archive, unpacked], {stdio: 'inherit'});
if (unzip.status !== 0) throw new Error('Could not extract the official UI archive');

function findDist(directory, depth = 0) {
  if (depth > 4) return undefined;
  const files = readdirSync(directory);
  if (files.includes('index.html') && files.some((name) => name.endsWith('.wasm'))) return directory;
  for (const name of files) {
    const candidate = path.join(directory, name);
    if (statSync(candidate).isDirectory()) {
      const found = findDist(candidate, depth + 1);
      if (found) return found;
    }
  }
  return undefined;
}

const officialDist = findDist(unpacked);
if (!officialDist) throw new Error('The archive does not contain a complete UI with index.html and WASM');
const stagedOutput = path.join(stagingRoot, 'dist');
cpSync(officialDist, stagedOutput, {recursive: true});
copyFileSync(path.join(root, 'licenses', 'perfetto-LICENSE.txt'), path.join(stagedOutput, 'perfetto-LICENSE.txt'));

const frontendBundlePath = path.join(stagedOutput, 'frontend_bundle.js');
let frontendBundle = readFileSync(frontendBundlePath, 'utf8');
const offlinePatches = [
  {
    from: 'var SCRIPT_LOAD_TIMEOUT_MS = 5e3;\n\tvar SCRIPT_URL = "https://storage.cloud.google.com/perfetto-ui-internal/internal-data-v1/amalgamated.js";',
    to: '// Local collaboration: remote legacy userscripts are disabled.',
  },
  {
    from: '\t\tconst scriptLoaded = defer();\n\t\tconst script = document.createElement("script");\n\t\tscript.src = SCRIPT_URL;\n\t\tscript.async = true;\n\t\tscript.onerror = () => scriptLoaded.resolve(globals);\n\t\tscript.onload = () => scriptLoaded.resolve(globals);\n\t\tdocument.head.append(script);\n\t\tsetTimeout(() => scriptLoaded.resolve(globals), SCRIPT_LOAD_TIMEOUT_MS);\n\t\treturn scriptLoaded;',
    to: '\t\treturn Promise.resolve(globals);',
  },
];
for (const patch of offlinePatches) {
  if (!frontendBundle.includes(patch.from)) {
    throw new Error(`Could not apply the required offline patch to ${frontendBundlePath}: ${patch.from.slice(0, 120)}`);
  }
  frontendBundle = frontendBundle.replace(patch.from, patch.to);
}
writeFileSync(frontendBundlePath, frontendBundle);

await build({
  entryPoints: [path.join(root, 'plugin', 'runtime.ts')],
  outfile: path.join(stagedOutput, 'collab.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  sourcemap: true,
  minify: false,
  legalComments: 'eof',
});

writeFileSync(path.join(stagedOutput, 'collab-bootstrap.js'), `(() => {
  try {
    const key = 'perfettoSettings';
    const settings = JSON.parse(localStorage.getItem(key) || '{}');
    settings.analyticsEnable = false;
    localStorage.setItem(key, JSON.stringify(settings));
    localStorage.removeItem('bypassDisabled');
  } catch (_) {}
})();\n`);

const indexPath = path.join(stagedOutput, 'index.html');
let html = readFileSync(indexPath, 'utf8');
if (!/<head[^>]*>/i.test(html) || !/<\/body>/i.test(html)) throw new Error('Unexpected official index.html structure');
html = html.replace(/<head[^>]*>/i, (match) => `${match}\n<script src="collab-bootstrap.js"></script>`);
html = html.replace(/<\/body>/i, '<script src="collab.js" defer></script>\n</body>');
writeFileSync(indexPath, html);

const manifest = {
  generatedBy: 'scripts/package-ui.mjs',
  officialRelease: release,
  officialArchive: path.basename(archive),
  officialArchiveSha256: archiveHash,
  parserVersion: 'perfetto-v59.1-official-ui',
  packagedAt: new Date().toISOString(),
};
writeFileSync(path.join(stagedOutput, 'collab-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(path.join(root, 'build-manifest.json'), `${JSON.stringify({...manifest, buildHost: 'official-release-ui', uiDir: output}, null, 2)}\n`);

if (existsSync(output)) rmSync(output, {recursive: true});
cpSync(stagedOutput, output, {recursive: true});
rmSync(stagingRoot, {recursive: true, force: true});
console.log(`Official ${release} UI and local collaboration plugin packaged at ${output}`);
console.log(`Official archive SHA-256: ${archiveHash}`);
